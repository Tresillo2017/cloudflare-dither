// Regenerates docs/coverage.md from the adapter list: which dithercn component each adapter uses.
// Usage: node scripts/coverage-doc.mjs
import { build } from 'esbuild';
import { mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const COMPONENTS_DIR = join(ROOT, 'vendor/dithercn/components/dithercn');
/** Data-only modules that are not components. */
const DATA_FILES = new Set(['world-land']);

const workDir = mkdtempSync(join(tmpdir(), 'dcf-coverage-'));
try {
  const outfile = join(workDir, 'adapters.mjs');
  await build({
    entryPoints: [join(ROOT, 'src/adapters/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    jsx: 'automatic',
    tsconfig: join(ROOT, 'tsconfig.json'),
    outfile,
    logLevel: 'error',
  });
  const { adapters } = await import(pathToFileURL(outfile).href);
  const components = readdirSync(COMPONENTS_DIR)
    .map((name) => name.replace(/\.(tsx|ts)$/, ''))
    .filter((name) => !DATA_FILES.has(name))
    .sort();

  const defaultOf = (users) => {
    if (users.length === 0) return 'n/a';
    const on = users.filter((adapter) => adapter.defaultEnabled).length;
    if (on === users.length) return 'on';
    return on === 0 ? 'off' : 'mixed';
  };
  const rows = components.map((component) => {
    const users = adapters.filter((adapter) => adapter.ditherComponents.includes(component));
    const where = users.length > 0 ? users.map((adapter) => `\`${adapter.id}\``).join(', ') : 'Dither Lab only';
    return `| \`${component}\` | ${where} | ${defaultOf(users)} |`;
  });
  const doc = [
    '# dithercn coverage',
    '',
    'Generated by `node scripts/coverage-doc.mjs`. Do not edit by hand.',
    '',
    'Every component in `vendor/dithercn/components/dithercn` is bundled and rendered in the Dither Lab.',
    'This table shows which dashboard adapters declare each one. Several adapters draw with the',
    'dithercn engine fills directly (`lib/dither`) instead of a packaged component, so they do not',
    'appear here.',
    '',
    'Default: `on` when every adapter using the component is on by default, `off` when none is,',
    '`mixed` otherwise, `n/a` when only the Lab renders it.',
    '',
    '| Component | Adapters | Default |',
    '|---|---|---|',
    ...rows,
    '',
  ].join('\n');
  writeFileSync(join(ROOT, 'docs/coverage.md'), doc);
  process.stdout.write(`docs/coverage.md: ${components.length} components, ${adapters.length} adapters\n`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
